"""Regenerate every brand- and token-dependent file from brand/brand.json and design/tokens.json (spec §2.3).

Run: `just brand` (or `uv run python tools/brand_sync.py`). Use `--check` in CI to fail when outputs are stale.
Identifiers in spec §2.2 (bundle IDs, package names) are never touched here.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLIENT = ROOT / "apps" / "client"
HEADER = "// GENERATED by tools/brand_sync.py — do not edit. Edit brand/brand.json or design/tokens.json.\n"


def dart_str(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def dart_color(value: str) -> str:
    if value.startswith("#"):
        return f"Color(0xFF{value[1:].upper()})"
    r, g, b, a = (float(x) for x in re.findall(r"[\d.]+", value))
    return f"Color.fromRGBO({int(r)}, {int(g)}, {int(b)}, {a})"


def brand_dart(brand: dict) -> str:
    keys = [
        "appName",
        "appNameHi",
        "tagline",
        "taglineHi",
        "legalEntity",
        "poweredBy",
        "poweredByHi",
        "supportEmail",
        "website",
        "fontFamily",
    ]
    lines = [f"  static const {k} = {dart_str(brand[k])};" for k in keys]
    return (
        HEADER
        + "\n/// Brand strings (placeholder brand, spec §2).\nabstract final class Brand {\n"
        + "\n".join(lines)
        + "\n}\n"
    )


STATUS_DART = {
    "listed": "listed",
    "newOrder": "newOrder",
    "adjourned": "adjourned",
    "urgent": "urgent",
    "disposed": "disposed",
    "success": "success",
    "ai": "ai",
}


def tokens_dart(tokens: dict) -> str:
    out = [
        HEADER,
        "// ignore_for_file: lines_longer_than_80_chars, public_member_api_docs\n",
        "import 'package:advocate_app/core/theme/app_colors.dart';",
        "import 'package:flutter/animation.dart';",
        "import 'package:flutter/painting.dart';\n",
    ]
    border = tokens["border"]
    for theme in ("light", "dark", "sunlight"):
        c = tokens["color"][theme]
        out.append(f"const {theme}Colors = AppColors(")
        for k, v in c.items():
            out.append(f"  {k}: {dart_color(v)},")
        out.append("  status: {")
        for k, (fg, bg) in tokens["color"]["status"][theme].items():
            out.append(f"    StatusKind.{STATUS_DART[k]}: StatusColors({dart_color(fg)}, {dart_color(bg)}),")
        out.append("  },")
        width = border["sunlight"] if theme == "sunlight" else border["default"]
        out.append(f"  borderWidth: {float(width)},")
        out.append(f"  isSunlight: {'true' if theme == 'sunlight' else 'false'},")
        out.append(");\n")

    out.append("abstract final class TypeTokens {")
    for name, t in tokens["type"].items():
        out.append(
            f"  static const {name} = TypeToken(size: {t['size']}, height: {t['height']}, weight: {t['weight']});"
        )
    out.append("}\n")

    out.append("abstract final class Space {")
    for v in tokens["space"]:
        out.append(f"  static const double s{v} = {v};")
    out.append(f"  static const double gutterPhone = {tokens['gutter']['phone']};")
    out.append(f"  static const double gutterDesktop = {tokens['gutter']['desktop']};")
    out.append("}\n")

    r = tokens["radius"]
    out.append("abstract final class Radii {")
    out.append(f"  static const double input = {r['input']};")
    out.append(f"  static const double card = {r['card']};")
    out.append(f"  static const double sheet = {r['sheet']};")
    out.append(f"  static const double focusRing = {border['focus']};")
    out.append("}\n")

    m = tokens["motion"]
    out.append("abstract final class MotionTokens {")
    for name in ("instant", "fast", "base", "slow"):
        out.append(f"  static const {name} = Duration(milliseconds: {m[name + 'Ms']});")
    out.append(f"  static const stagger = Duration(milliseconds: {m['staggerMs']});")
    out.append(f"  static const staggerMaxItems = {m['staggerMaxItems']};")
    for name, (a, b, c2, d) in m["easing"].items():
        out.append(f"  static const {name} = Cubic({a}, {b}, {c2}, {d});")
    s = m["spring"]
    out.append(
        "  static const spring = SpringDescription("
        f"mass: {s['mass']}, stiffness: {s['stiffness']}, damping: {s['damping']});"
    )
    out.append("}\n")
    return "\n".join(out)


def android_strings(name: str) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by tools/brand_sync.py — do not edit. -->\n'
        f'<resources>\n    <string name="app_name">{name}</string>\n</resources>\n'
    )


def ios_infoplist_strings(name: str) -> str:
    header = "/* GENERATED by tools/brand_sync.py — do not edit. */\n"
    return f'{header}"CFBundleDisplayName" = "{name}";\n"CFBundleName" = "{name}";\n'


def patch(path: Path, pattern: str, replacement: str) -> str:
    return patch_text(path.read_text(encoding="utf-8"), pattern, replacement)


def outputs(brand: dict, tokens: dict) -> dict[Path, str]:
    name, name_hi = brand["appName"], brand["appNameHi"]
    files = {
        CLIENT / "lib/core/brand/brand.g.dart": brand_dart(brand),
        CLIENT / "lib/core/theme/tokens.g.dart": tokens_dart(tokens),
        CLIENT / "android/app/src/main/res/values/strings.xml": android_strings(name),
        CLIENT / "android/app/src/main/res/values-hi/strings.xml": android_strings(name_hi),
        CLIENT / "ios/Runner/en.lproj/InfoPlist.strings": ios_infoplist_strings(name),
        CLIENT / "ios/Runner/hi.lproj/InfoPlist.strings": ios_infoplist_strings(name_hi),
    }
    manifest = CLIENT / "android/app/src/main/AndroidManifest.xml"
    files[manifest] = patch(manifest, r'android:label="[^"]*"', 'android:label="@string/app_name"')
    plist = CLIENT / "ios/Runner/Info.plist"
    text = patch(plist, r"(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)", rf"\g<1>{name}\g<2>")
    files[plist] = re.sub(r"(<key>CFBundleName</key>\s*<string>)[^<]*(</string>)", rf"\g<1>{name}\g<2>", text)
    rc = CLIENT / "windows/runner/Runner.rc"
    text = patch(rc, r'(VALUE "FileDescription", ")[^"]*(")', rf"\g<1>{name}\g<2>")
    text = patch_text(text, r'(VALUE "ProductName", ")[^"]*(")', rf"\g<1>{name}\g<2>")
    text = patch_text(text, r'(VALUE "CompanyName", ")[^"]*(")', rf"\g<1>{brand['legalEntity']}\g<2>")
    files[rc] = patch_text(
        text, r'(VALUE "LegalCopyright", ")[^"]*(")', rf"\g<1>Copyright (C) {brand['legalEntity']}\g<2>"
    )
    main_cpp = CLIENT / "windows/runner/main.cpp"
    files[main_cpp] = patch(main_cpp, r'window\.Create\(L"[^"]*"', f'window.Create(L"{name}"')
    return files


def patch_text(text: str, pattern: str, replacement: str) -> str:
    new, n = re.subn(pattern, replacement, text)
    if n == 0:
        raise SystemExit(f"brand_sync: pattern not found: {pattern}")
    return new


def main() -> int:
    brand = json.loads((ROOT / "brand/brand.json").read_text(encoding="utf-8"))
    tokens = json.loads((ROOT / brand["tokens"]).read_text(encoding="utf-8"))
    check = "--check" in sys.argv
    stale = []
    for path, content in outputs(brand, tokens).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\r\n" if path.suffix == ".rc" else "\n")
    for p in stale:
        print(f"{'stale' if check else 'wrote'}: {p}")
    return 1 if check and stale else 0


if __name__ == "__main__":
    assert dart_color("#3730a3") == "Color(0xFF3730A3)"
    assert dart_color("rgba(22,24,29,0.45)") == "Color.fromRGBO(22, 24, 29, 0.45)"
    assert dart_str("it's $x") == "'it\\'s \\$x'"
    sys.exit(main())

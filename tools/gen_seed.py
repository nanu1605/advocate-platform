"""Generate supabase/seed/010_reference.sql from config/plans.yaml plus the default feature flags.
Run: `just seed-gen`; CI runs `--check` so the SQL never drifts from the YAML."""

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "supabase/seed/010_reference.sql"
# Later-phase entry points stay hidden until their phase (spec §5.2).
FLAGS = ["ask", "voice", "scan_to_case", "brief_me", "drafting", "research", "strategy"]


def lit(value: object) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def render() -> str:
    plans = yaml.safe_load((ROOT / "config/plans.yaml").read_text(encoding="utf-8"))["plans"]
    lines = ["-- GENERATED by tools/gen_seed.py from config/plans.yaml — do not edit.", ""]
    for p in plans:
        lines.append(
            "insert into public.plans (id, name, price_paise, interval, limits) values "
            f"({lit(p['id'])}, {lit(p['name'])}, {int(p['price_paise'])}, {lit(p['interval'])}, "
            f"{lit(json.dumps(p['limits'], sort_keys=True))}::jsonb)\n"
            "  on conflict (id) do update set name = excluded.name, price_paise = excluded.price_paise, "
            "interval = excluded.interval, limits = excluded.limits;"
        )
    lines.append("")
    for key in FLAGS:
        lines.append(
            f"insert into public.feature_flags (key, value) values ({lit(key)}, 'false') on conflict (key) do nothing;"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != content
        print("stale: " + str(OUT.relative_to(ROOT)) if stale else "seed up to date")
        return int(stale)
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    assert lit("it's") == "'it''s'"
    sys.exit(main())
